export function instantiateCompositeTemplate(templateId: string, existingIds: Set<string>): ArchBlock | null {
  const tpl = STARTER_COMPOSITE_TEMPLATES.find((t) => t.templateId === templateId || t.id === templateId);
  if (!tpl) return null;
  const base = `blk-${templateId}`;
  let id = base;
  let seq = 2;
  while (existingIds.has(id)) {
    id = `${base}-${seq}`;
    seq += 1;
  }
  return {
    ...tpl,
    id,
    memberRefdes: [...tpl.memberRefdes],
    x: tpl.x + (seq - 2) * 32,
    y: tpl.y + (seq - 2) * 28,
  };
}

