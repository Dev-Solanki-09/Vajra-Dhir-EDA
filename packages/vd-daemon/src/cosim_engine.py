def generate_firmware_and_digital_twin(
    con: Optional[sqlite3.Connection],
    project_dir: Optional[pathlib.Path] = None,
    wiring_overrides: Optional[Dict[str, Any]] = None,
    code_i2c_addr: int = 0x76,
) -> Dict[str, Any]:
    if project_dir is None:
        _ensure_active_workspace()
        project_dir = pathlib.Path(_ACTIVE_STATE["project_dir"])
    project_dir = pathlib.Path(project_dir)

    live_comp_defs = ""
    live_pinmux_defs = ""
    zephyr_overlay_nodes: List[str] = []
    mcu_target = "STM32F401RE"
    if con is not None:
        try:
            comp_rows = con.execute("SELECT refdes, value_str, mpn FROM components WHERE COALESCE(deleted, 0) = 0 ORDER BY refdes").fetchall()
            for r_ref, r_val, r_mpn in comp_rows:
                txt_u = f"{r_val or ''} {r_mpn or ''}".upper()
                if "ESP32-S3" in txt_u or "ESP32S3" in txt_u:
                    mcu_target = "ESP32-S3-WROOM-1"
                elif "STM32G4" in txt_u:
                    mcu_target = "STM32G474RET6"
                elif "RP2040" in txt_u:
                    mcu_target = "RP2040"
                safe_r = "".join(ch if ch.isalnum() else "_" for ch in str(r_ref).upper())
                live_comp_defs += f'#define VD_HW_{safe_r}_VALUE "{r_val}"\n'
            pm_rows = con.execute("SELECT mcu_refdes, pin_number, peripheral_instance, signal_alias, gpio_mode FROM firmware_pinmux ORDER BY signal_alias").fetchall()
            for mcu, pnum, periph, alias, mode in pm_rows:
                safe_a = "".join(ch if ch.isalnum() else "_" for ch in str(alias).upper())
                live_pinmux_defs += f'#define VD_HWIR_{safe_a} "{pnum}" /* {mcu} {periph} ({mode}) */\n'
                zephyr_overlay_nodes.append(f'/* {alias} -> {mcu} pin {pnum} ({periph}, {mode}) */')
        except Exception:
            pass

    board_pins_h = f"""/* Auto-generated by Vajra-Dhir EDA Prompt 11 HW-IR -> Firmware Generator */
#ifndef VAJRA_BOARD_PINS_H
#define VAJRA_BOARD_PINS_H

#define VD_MCU_TARGET "{mcu_target}"
#define VD_PIN_LED_STATUS PA5
#define VD_PIN_I2C1_SCL PB6
#define VD_PIN_I2C1_SDA PB7
#define VD_PIN_UART1_TX PA9
#define VD_PIN_UART1_RX PA10
#define VD_PIN_BUCK_PWM PA8
#define VD_I2C_SENSOR_ADDR {hex(code_i2c_addr)}
#define VD_ADC_VBUS_DIVIDER_SCALE 4.0f
#define VD_ADC_VREF_MV 3300

{live_comp_defs}{live_pinmux_defs}#endif /* VAJRA_BOARD_PINS_H */
"""

    board_pins_rs = f"""// Auto-generated by Vajra-Dhir EDA Prompt 11 HW-IR -> Firmware Generator
pub const VD_MCU_TARGET: &str = "STM32F401RE";
pub const VD_PIN_LED_STATUS: &str = "PA5";
pub const VD_PIN_I2C1_SCL: &str = "PB6";
pub const VD_PIN_I2C1_SDA: &str = "PB7";
pub const VD_PIN_UART1_TX: &str = "PA9";
pub const VD_PIN_UART1_RX: &str = "PA10";
pub const VD_I2C_SENSOR_ADDR: u8 = {hex(code_i2c_addr)};
pub const VD_ADC_VBUS_DIVIDER_SCALE: f32 = 4.0;
"""

    board_config_py = f"""\"\"\"Auto-generated SBC & MCU Virtual Hardware Pin/Bus Configuration.\"\"\"

MCU_TARGET = "STM32F401RE"
I2C_BUS_ID = 1
I2C_SENSOR_ADDR = {hex(code_i2c_addr)}
UART_PORT = "/dev/ttyAMA0"
UART_BAUD = 115200
GPIO_LED_PIN = "PA5"
ADC_VBUS_DIVIDER_RATIO = 4.0
"""

    controller_py = f"""\"\"\"Real SBC/MCU control script targeting exact board_config bindings.\"\"\"

I2C_SENSOR_ADDR = {hex(code_i2c_addr)}


def run_board_firmware(v_i2c, v_uart, v_gpio, log):
    log(f"Init controller for I2C sensor @ {{hex(I2C_SENSOR_ADDR)}}")
    chip_id = v_i2c.read_byte_data(I2C_SENSOR_ADDR, 0xD0)
    log(f"I2C BME280 chip_id = {{hex(chip_id)}}")
    resp = v_uart.loopback_echo("SELF_TEST_OK")
    if not resp.startswith("ACK:"):
        raise RuntimeError("UART1 telemetry handshake failed (zero RX bytes)")
    v_gpio.write("PA5", 1)
    v_gpio.write("PA5", 0)
    v_gpio.write("PA5", 1)
    log("PASS: Firmware self-test + LED blink + telemetry verified.")
"""

    # Reference upstream Renode STM32F4 template + board peripherals
    renode_tpl = _ROOT / "vendor" / "ring1-refs" / "renode" / "platforms" / "cpus" / "stm32f4.repl"
    repl_header = f"// Template reference: {renode_tpl.name} (renode/renode MIT)"
    board_repl = f"""{repl_header}
using "platforms/cpus/stm32f4.repl"

ledStatus: Miscellaneous.LED @ gpioPortA 5
gpioPortA:
    5 -> ledStatus@0

i2cSensorBme280: Sensors.BME280 @ i2c1 {hex(code_i2c_addr)}
"""

    wiring: Dict[str, Any] = {
        "board": "golden-buck-mcu",
        "mcu": "STM32F401RE",
        "i2c1": {
            "scl_pin": "PB6",
            "sda_pin": "PB7",
            "has_sda_pullup": True,
            "has_scl_pullup": True,
            "device_addr": 0x76,
        },
        "uart1": {
            "tx_pin": "PA9",
            "rx_pin": "PA10",
            "tx_rx_swapped": False,
        },
        "gpio": {
            "led_pin": "PA5",
            "led_refdes": "D1",
            "led_active_high": True,
        },
        "power": {
            "rail_net": "+3.3V",
            "c_out_uf": 22.0,
            "load_current_a": 0.6,
        },
    }

    if con is not None:
        try:
            nets = [str(r[0]) for r in con.execute("SELECT name FROM nets").fetchall()]
            wiring["hwir_net_count"] = len(nets)
        except Exception:
            pass

    if wiring_overrides:
        for section, vals in wiring_overrides.items():
            if isinstance(vals, dict) and isinstance(wiring.get(section), dict):
                wiring[section].update(vals)
            else:
                wiring[section] = vals

    files_written: List[str] = []
    targets = {
        "firmware/include/board_pins.h": board_pins_h,
        "firmware/include/board_pins.rs": board_pins_rs,
        "firmware/sbc/board_config.py": board_config_py,
        "firmware/sbc/controller.py": controller_py,
        "sim/board.repl": board_repl,
        "sim/wiring.json": json.dumps(wiring, indent=2),
    }
    for rel, content in targets.items():
        dst = project_dir / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        write_text_atomic(dst, content)
        files_written.append(rel)

    elf_path = build_minimal_arm_elf(project_dir / "sim" / "stm32_blink_i2c.elf")
    files_written.append("sim/stm32_blink_i2c.elf")

    return {
        "ok": True,
        "project_dir": str(project_dir),
        "files": files_written,
        "wiring": wiring,
        "controller_py": controller_py,
        "board_pins_h": board_pins_h,
        "board_repl": board_repl,
        "elf_path": str(elf_path),
        "renode": find_renode_executable(),
    }


def execute_cosim_scenario(
    con: Optional[sqlite3.Connection],
    project_dir: Optional[pathlib.Path] = None,
    scenario: str = "nominal",
    wiring_overrides: Optional[Dict[str, Any]] = None,
    code_i2c_addr: Optional[int] = None,
) -> Dict[str, Any]:
    overrides = copy.deepcopy(wiring_overrides) if wiring_overrides else {}
    addr_in_code = int(code_i2c_addr) if code_i2c_addr is not None else 0x76

    if scenario == "missing_i2c_pullup":
        overrides.setdefault("i2c1", {})["has_sda_pullup"] = False
        overrides["i2c1"]["has_scl_pullup"] = False
    elif scenario == "swapped_uart":
        overrides.setdefault("uart1", {})["tx_rx_swapped"] = True
    elif scenario == "i2c_addr_mismatch":
        overrides.setdefault("i2c1", {})["device_addr"] = 0x77
        addr_in_code = 0x76 if code_i2c_addr is None else int(code_i2c_addr)

    gen = generate_firmware_and_digital_twin(
        con,
        project_dir=project_dir,
        wiring_overrides=overrides,
        code_i2c_addr=addr_in_code,
    )

    proc = subprocess.run(
        [sys.executable, str(_COSIM_WORKER)],
        input=json.dumps({
            "wiring": gen["wiring"],
            "sbc_script": gen["controller_py"],
            "elf_path": gen["elf_path"],
        }),
        text=True,
        capture_output=True,
        timeout=30,
        check=False,
    )
    if proc.returncode != 0 or not proc.stdout.strip():
        return {"ok": False, "scenario": scenario, "error": proc.stderr or f"worker exit={proc.returncode}"}

    sim = json.loads(proc.stdout)
    sim["scenario"] = scenario
    sim["generated_files"] = gen["files"]
    sim["wiring"] = gen["wiring"]
    sim["board_pins_h"] = gen["board_pins_h"]
    sim["board_repl"] = gen["board_repl"]
    return sim


def run_4_cosim_fault_suite(
    con: Optional[sqlite3.Connection],
    project_dir: Optional[pathlib.Path] = None,
) -> Dict[str, Any]:
    cases = [
        ("nominal", None),
        ("missing_i2c_pullup", "COSIM_I2C_MISSING_PULLUP_NACK"),
        ("swapped_uart", "COSIM_UART_TX_RX_SWAPPED"),
        ("i2c_addr_mismatch", "COSIM_I2C_ADDRESS_MISMATCH"),
    ]
    results: List[Dict[str, Any]] = []
    for scen, expected_rule in cases:
        res = execute_cosim_scenario(con, project_dir=project_dir, scenario=scen)
        rules = [s["rule_id"] for s in res.get("shortcomings", [])]
        passed_gate = res["ok"] if expected_rule is None else (not res["ok"] and expected_rule in rules)
        results.append({
            "scenario": scen,
            "expected_rule": expected_rule,
            "gate_ok": passed_gate,
            "result": res,
        })
    return {
        "total": len(results),
        "all_gates_passed": all(r["gate_ok"] for r in results),
        "cases": results,
    }
